function transformStrings(value, transform) {
  if (typeof value === 'string') return transform(value)
  if (Array.isArray(value)) return value.map(item => transformStrings(item, transform))
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value).map(([key, child]) => [key, transformStrings(child, transform)])
    )
  }
  return value
}

function toVueInterpolation(input) {
  return input.replace(/\{\{(\w+)\}\}/g, '{$1}')
}

export function getCanonicalMessages() {
  return { en, zh }
}

export function getVueMessages() {
  return {
    en: transformStrings(en, toVueInterpolation),
    zh: transformStrings(zh, toVueInterpolation),
  }
}

export function getI18nextResources() {
  return {
    en: { translation: en },
    zh: { translation: zh },
  }
}

